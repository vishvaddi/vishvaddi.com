import { chromium } from 'playwright-core'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { serveBuiltSite } from './serve-built-site.mjs'
const server = await serveBuiltSite(4417)
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--autoplay-policy=no-user-gesture-required', '--mute-audio'] })
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
await context.route('**/api/metric', route => route.fulfill({ status: 204 }))
const page = await context.newPage(), errors = []
page.on('pageerror', e => errors.push(e.message))
await mkdir('.snapshots', { recursive: true })
const choose = (label, value) => page.locator('.musical').getByLabel(label, { exact: true }).selectOption(value)
try {
  await page.goto(`${server.base}/audio/chords/`)
  await page.locator('.musical h2').waitFor()
  await choose('Key', '9'); await choose('Scale', 'minor')
  assert.match(await page.locator('.musical-pads').textContent(), /Am/)
  await page.getByRole('button', { name: 'Fretboard', exact: true }).click()
  assert.equal(await page.locator('.musical-frets button').count(), 78)
  await page.getByText('Pattern & guitar settings', { exact: true }).click()
  await choose('Tuning', 'dropD'); await choose('Hand', 'true'); await choose('Arpeggiator', 'up')
  assert.equal(await page.locator('.musical-frets tr').last().locator('button').last().getAttribute('aria-label'), 'Play D2, degree 4')
  await page.getByRole('button', { name: 'Loop progression', exact: true }).click()
  assert.equal(await page.getByRole('button', { name: 'Stop loop', exact: true }).getAttribute('aria-pressed'), 'true')
  await page.getByRole('button', { name: 'Sound off', exact: true }).click()
  await page.getByRole('button', { name: 'Open in Studio', exact: true }).click()
  await page.locator('.wa-transport').waitFor()
  assert.equal(await page.locator('.wa-page-synth').isVisible(), true)
  await page.locator('.wa-combinator-host:visible').waitFor()
  assert.equal(await page.locator('.musical').getByLabel('Key', { exact: true }).inputValue(), '9')
  const read = () => page.evaluate(() => JSON.parse(localStorage.getItem('vv_studio_v2')))
  await page.waitForTimeout(600)
  const before = await read(), count = p => Object.values(p.synthLaneNotes).flat(2).length
  assert.equal(before.title, 'USE YOUR HEART — INTERLUDE STUDY')
  assert.equal(before.bpm, 111.5)
  assert.equal(await page.locator('.wa-song-library select option[value^="factory:"]').count(), 1)
  assert.ok(Object.values(before.synthLaneNotes).flat(2).every(n => n.step >= 0 && n.len > 0 && n.step + n.len <= 32))
  await page.getByRole('button', { name: 'Add pattern to clip', exact: true }).click()
  assert.match(await page.locator('.musical-status').textContent(), /Added 4 bars/)
  await page.waitForTimeout(600)
  const after = await read()
  assert.equal(count(after), count(before) + 32)
  await page.locator('.wa-transport button[aria-label="Undo"]').click()
  await page.waitForTimeout(600)
  assert.equal(count(await read()), count(before))
  await page.locator('.wa-transport button[aria-label="Redo"]').click()
  await page.waitForTimeout(600)
  assert.equal(count(await read()), count(after))
  await page.getByText('Performance macros', { exact: true }).click()
  await page.locator('.musical').getByLabel('Brightness', { exact: true }).fill('0.7')
  await page.locator('.musical').getByLabel('Brightness', { exact: true }).dispatchEvent('input')
  await page.waitForTimeout(600)
  assert.ok((await read()).synthPatches.bass.filter.cutoff > 2000)
  await page.reload(); await page.locator('.wa-combinator-host:visible').waitFor()
  assert.equal(count(await read()), count(after))
  assert.equal(await page.locator('.musical').getByLabel('Key', { exact: true }).inputValue(), '9')
  await page.getByRole('button', { name: 'Loop progression', exact: true }).click()
  await page.locator('.wa-transport').getByRole('button', { name: 'Stop', exact: true }).click()
  assert.equal(await page.getByRole('button', { name: 'Loop progression', exact: true }).getAttribute('aria-pressed'), 'false')
  await page.screenshot({ path: '.snapshots/combinator-desktop.png' })
  for (const viewport of [{ width: 390, height: 844 }, { width: 844, height: 390 }]) {
    await page.setViewportSize(viewport)
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2))
    await page.getByRole('button', { name: 'Fretboard', exact: true }).click()
    await page.screenshot({ path: `.snapshots/combinator-${viewport.width}.png` })
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(`${server.base}/audio/ear/#x=keySignature&v=staff&seed=5`)
  await page.locator('.ear-staff').waitFor()
  assert.equal(await page.locator('.ear-choice').count(), 12)
  await page.locator('#ear-session').click()
  await page.locator('.ear-choice').first().click()
  assert.match(await page.locator('#ear-topics').textContent(), /Key signature:.*\/1/)
  await page.locator('#ear-session').click()
  assert.match(await page.locator('#ear-session-status').textContent(), /Session complete/)
  await page.locator('[data-exercise="scale"]').click()
  assert.equal(await page.locator('.ear-choice').count(), 8)
  await page.locator('#ear-silence').click()
  await page.goto(`${server.base}/site/investment/`)
  assert.equal(await page.locator('#investment-results tr').count(), 27)
  await page.locator('[name="brokerage"]').fill('0')
  await page.getByRole('button', { name: 'Compare schedules' }).click()
  assert.match(await page.locator('#investment-summary').textContent(), /1 fortnight/)
  await page.locator('[name="returnRate"]').fill('-20')
  await page.getByRole('button', { name: 'Compare schedules' }).click()
  assert.match(await page.locator('#investment-summary').textContent(), /Savings only/)
  await page.setViewportSize({ width: 390, height: 844 })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2))
  await page.screenshot({ path: '.snapshots/investment-phone.png', fullPage: true })
  assert.deepEqual(errors, [])
  console.log('PASS: explorer, Studio handoff, clip insertion/persistence, macros, stop, phone layouts, practice and investment calculator')
} finally { await browser.close(); await server.close() }
